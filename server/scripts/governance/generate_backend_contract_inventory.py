#!/usr/bin/env python3
"""Generate a deterministic, review-oriented backend contract inventory."""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs/project/BACKEND_CONTRACT_INVENTORY.md"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def openapi_paths(text: str) -> list[str]:
    return sorted(set(re.findall(r"(?m)^  (/[^:\r\n]+):\s*$", text)))


def permission_mappings(text: str) -> list[tuple[str, str, str]]:
    pattern = re.compile(
        r'add\(METHOD_(GET|POST|PUT|DELETE|PATCH),\s*"([^"]+)",\s*"([^"]+)"\);'
    )
    return sorted(set(pattern.findall(text)), key=lambda value: (value[1], value[0], value[2]))


def alias_declarations(java_files: list[Path]) -> list[tuple[str, int, str]]:
    found: list[tuple[str, int, str]] = []
    pattern = re.compile(r"@(RequestMapping|GetMapping|PostMapping|PutMapping|DeleteMapping|PatchMapping)\([^\r\n]*\{[^\r\n]*\}")
    for path in java_files:
        for line_number, line in enumerate(read(path).splitlines(), start=1):
            if pattern.search(line) and line.count('"') >= 4:
                found.append((path.relative_to(ROOT).as_posix(), line_number, line.strip()))
    return sorted(found)


def api_error_codes(java_files: list[Path]) -> list[tuple[str, int]]:
    counter: Counter[str] = Counter()
    pattern = re.compile(r'new\s+ApiException\(\s*\d+\s*,\s*"([A-Z][A-Z0-9_]+)"')
    for path in java_files:
        counter.update(pattern.findall(read(path)))
    return sorted(counter.items())


def numeric_error_codes(java_files: list[Path]) -> list[tuple[str, int]]:
    counter: Counter[str] = Counter()
    pattern = re.compile(r'\bR\.error\(\s*(\d{3,6})\s*[,)]')
    for path in java_files:
        counter.update(pattern.findall(read(path)))
    return sorted(counter.items(), key=lambda value: int(value[0]))


def status_constants(java_files: list[Path]) -> list[tuple[str, str, str]]:
    pattern = re.compile(
        r'public\s+static\s+final\s+String\s+((?:STATUS|STATE|RESULT|AUTHORITY_MODE)_[A-Z0-9_]+)\s*=\s*"([^"]+)"'
    )
    found: list[tuple[str, str, str]] = []
    for path in java_files:
        for name, value in pattern.findall(read(path)):
            found.append((path.relative_to(ROOT).as_posix(), name, value))
    return sorted(set(found))


def render() -> str:
    java_root = ROOT / "src/main/java"
    java_files = sorted(java_root.rglob("*.java"))
    paths = openapi_paths(read(ROOT / "docs/openapi.yaml"))
    permissions = permission_mappings(read(ROOT / "src/main/java/com/lanf/config/ApiPermissionMapping.java"))
    aliases = alias_declarations(java_files)
    string_errors = api_error_codes(java_files)
    numeric_errors = numeric_error_codes(java_files)
    states = status_constants(java_files)

    lines = [
        "# Backend Contract Inventory",
        "",
        "> Generated by `scripts/governance/generate_backend_contract_inventory.py`. Do not edit manually.",
        "> This is a static audit snapshot, not a replacement for `docs/openapi.yaml`, runtime authorization, or domain state machines.",
        "",
        "## Summary",
        "",
        f"- OpenAPI paths: {len(paths)}",
        f"- Built-in API permission mappings: {len(permissions)}",
        f"- Multi-route alias declarations: {len(aliases)}",
        f"- Structured ApiException codes: {len(string_errors)}",
        f"- Numeric R.error codes: {len(numeric_errors)}",
        f"- Public status/state constants: {len(states)}",
        "",
        "## OpenAPI Paths",
        "",
    ]
    lines.extend(f"- `{path}`" for path in paths)
    lines.extend(["", "## Built-in API Permission Mappings", "", "| Method | Path pattern | Permission expression |", "|---|---|---|"])
    lines.extend(f"| {method} | `{path}` | `{permission}` |" for method, path, permission in permissions)
    lines.extend(["", "## Multi-route Alias Declarations", "", "| Source | Line | Declaration |", "|---|---:|---|"])
    lines.extend(f"| `{source}` | {line} | `{declaration.replace('|', '\\|')}` |" for source, line, declaration in aliases)
    lines.extend(["", "## Structured ApiException Codes", "", "| Error code | Static occurrences |", "|---|---:|"])
    lines.extend(f"| `{code}` | {count} |" for code, count in string_errors)
    lines.extend(["", "## Numeric R.error Codes", "", "| Code | Static occurrences |", "|---|---:|"])
    lines.extend(f"| `{code}` | {count} |" for code, count in numeric_errors)
    lines.extend(["", "## Public Status / State Constants", "", "| Source | Constant | Value |", "|---|---|---|"])
    lines.extend(f"| `{source}` | `{name}` | `{value}` |" for source, name, value in states)
    lines.extend([
        "",
        "## Known Static-analysis Limits",
        "",
        "- OpenAPI inventory lists path keys; operations and schemas remain authoritative in `docs/openapi.yaml`.",
        "- Permission inventory covers the built-in fallback map only; database overrides remain runtime inputs.",
        "- Alias inventory covers same-line annotation arrays and intentionally flags compatibility surface rather than reconstructing every resolved route.",
        "- Error/status inventories cover literal declarations and calls; dynamically composed values are not inferred.",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        current = read(OUTPUT) if OUTPUT.is_file() else ""
        if current != generated:
            print(f"CONTRACT INVENTORY: FAIL ({OUTPUT.relative_to(ROOT)} is stale)")
            return 2
        print("CONTRACT INVENTORY: PASS")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
