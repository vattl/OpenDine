CREATE TABLE IF NOT EXISTS t_wechat_native_payment_attempt (
    id BIGINT NOT NULL AUTO_INCREMENT,
    shop_id INT NOT NULL,
    order_id INT NOT NULL,
    order_no VARCHAR(64) NOT NULL,
    out_trade_no VARCHAR(32) NOT NULL,
    merchant_id VARCHAR(32) NOT NULL DEFAULT '1',
    amount_fen INT NOT NULL,
    code_url VARCHAR(512) NULL,
    status VARCHAR(24) NOT NULL,
    trade_state VARCHAR(32) NULL,
    transaction_id VARCHAR(64) NULL,
    active_key VARCHAR(160) NULL,
    terminal_id VARCHAR(64) NULL,
    expires_at DATETIME NULL,
    success_time DATETIME NULL,
    last_queried_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_wx_native_out_trade_no (out_trade_no),
    UNIQUE KEY uk_wx_native_active_key (active_key),
    KEY idx_wx_native_shop_order (shop_id, order_no, id),
    KEY idx_wx_native_status_expire (status, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='微信Native扫码支付尝试';
