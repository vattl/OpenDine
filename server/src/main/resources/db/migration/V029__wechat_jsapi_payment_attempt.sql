CREATE TABLE IF NOT EXISTS t_wechat_jsapi_payment_attempt (
    id BIGINT NOT NULL AUTO_INCREMENT,
    shop_id INT NOT NULL,
    order_id INT NOT NULL,
    order_no VARCHAR(64) NOT NULL,
    out_trade_no VARCHAR(32) NOT NULL,
    merchant_id VARCHAR(32) NOT NULL DEFAULT '1',
    merchant_config_id BIGINT NOT NULL,
    merchant_key VARCHAR(64) NULL,
    merchant_config_version INT NOT NULL,
    amount_fen INT NOT NULL,
    payer_openid VARCHAR(128) NOT NULL,
    prepay_id VARCHAR(128) NULL,
    status VARCHAR(24) NOT NULL,
    trade_state VARCHAR(32) NULL,
    transaction_id VARCHAR(64) NULL,
    active_key VARCHAR(160) NULL,
    expires_at DATETIME NULL,
    success_time DATETIME NULL,
    last_queried_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_wx_jsapi_out_trade_no (out_trade_no),
    UNIQUE KEY uk_wx_jsapi_active_key (active_key),
    KEY idx_wx_jsapi_shop_order (shop_id, order_no, id),
    KEY idx_wx_jsapi_status_expire (status, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='微信JSAPI支付尝试';
